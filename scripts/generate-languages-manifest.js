#!/usr/bin/env node

/**
 * generate-languages-manifest.js
 * ────────────────────────────────────────────────────────────────────────────
 * Scans /lang folder and generates data/languages.json manifest
 * 
 * Usage:
 *   node scripts/generate-languages-manifest.js
 * 
 * Output:
 *   data/languages.json
 * 
 * This removes all hardcoded language lists from the codebase.
 */

const fs = require('fs');
const path = require('path');

// Directories to scan
const PROJECT_ROOT = path.resolve(__dirname, '..');
const LANG_DIR = path.join(PROJECT_ROOT, 'lang');
const OUTPUT_FILE = path.join(PROJECT_ROOT, 'data', 'languages.json');

// Read config.js to get default language
function getDefaultLanguageFromConfig() {
  try {
    const configPath = path.join(PROJECT_ROOT, 'js', 'config.js');
    const configContent = fs.readFileSync(configPath, 'utf-8');
    const match = configContent.match(/defaultLanguage:\s*["']([^"']+)["']/);
    return match ? match[1] : 'en';
  } catch (error) {
    console.warn('Could not read config.js, using default "en"');
    return 'en';
  }
}

// Scan /lang folder for language directories
function scanLanguageDirectories() {
  try {
    const entries = fs.readdirSync(LANG_DIR, { withFileTypes: true });
    const languages = entries
      .filter(entry => entry.isDirectory())
      .map(entry => entry.name)
      .sort();
    
    if (languages.length === 0) {
      throw new Error('No language directories found in /lang');
    }
    
    return languages;
  } catch (error) {
    console.error(`Error scanning ${LANG_DIR}:`, error.message);
    process.exit(1);
  }
}

// Validate that each language has required files
function validateLanguages(languages) {
  const REQUIRED_FILES = ['common.json'];
  const issues = [];
  
  languages.forEach(lang => {
    const langPath = path.join(LANG_DIR, lang);
    REQUIRED_FILES.forEach(file => {
      const filePath = path.join(langPath, file);
      if (!fs.existsSync(filePath)) {
        issues.push(`❌ Missing ${lang}/${file}`);
      }
    });
  });
  
  if (issues.length > 0) {
    console.warn('\n⚠️  Validation warnings:');
    issues.forEach(issue => console.warn(`   ${issue}`));
    console.warn('');
  }
  
  return issues.length === 0;
}

// Build region → language mappings from countries.json if available
function buildRegionMappings() {
  try {
    const countriesPath = path.join(PROJECT_ROOT, 'data', 'countries.json');
    if (!fs.existsSync(countriesPath)) {
      return {};
    }
    
    const countries = JSON.parse(fs.readFileSync(countriesPath, 'utf-8'));
    const mappings = {};
    
    countries.forEach(country => {
      if (country.code && country.lang_code) {
        mappings[country.code] = country.lang_code;
      }
    });
    
    return mappings;
  } catch (error) {
    console.warn('Could not build region mappings from countries.json');
    return {};
  }
}

// Generate manifest
function generateManifest(languages, defaultLanguage) {
  const timestamp = new Date().toISOString();
  
  const manifest = {
    // Version for cache busting
    version: '1.0.0',
    
    // Timestamp for debugging
    generated: timestamp,
    
    // List of all supported languages
    languages: languages,
    
    // Default/fallback language (from config.js)
    default: defaultLanguage,
    
    // Count for reference
    count: languages.length,
    
    // Region → language code mappings (for geolocation)
    regionMappings: buildRegionMappings(),
    
    // Notes for developers
    note: 'Generated by scripts/generate-languages-manifest.js - DO NOT EDIT MANUALLY'
  };
  
  return manifest;
}

// Write manifest to file
function writeManifest(manifest) {
  try {
    // Ensure data directory exists
    const dataDir = path.dirname(OUTPUT_FILE);
    if (!fs.existsSync(dataDir)) {
      fs.mkdirSync(dataDir, { recursive: true });
    }
    
    // Write with nice formatting
    fs.writeFileSync(OUTPUT_FILE, JSON.stringify(manifest, null, 2));
    console.log(`✅ Generated: ${path.relative(PROJECT_ROOT, OUTPUT_FILE)}`);
    
    return true;
  } catch (error) {
    console.error(`Error writing manifest:`, error.message);
    process.exit(1);
  }
}

// Main execution
function main() {
  console.log('\n📦 Generating languages manifest...\n');
  
  // Step 1: Get default language from config
  const defaultLanguage = getDefaultLanguageFromConfig();
  console.log(`   Default language: ${defaultLanguage}`);
  
  // Step 2: Scan language directories
  const languages = scanLanguageDirectories();
  console.log(`   Found ${languages.length} languages: ${languages.join(', ')}\n`);
  
  // Step 3: Validate languages
  const isValid = validateLanguages(languages);
  if (!isValid) {
    console.log('   Proceeding anyway...\n');
  }
  
  // Step 4: Generate manifest
  const manifest = generateManifest(languages, defaultLanguage);
  
  // Step 5: Write to file
  writeManifest(manifest);
  
  // Step 6: Show summary
  console.log(`\n📋 Manifest Summary:`);
  console.log(`   Languages:  ${manifest.count}`);
  console.log(`   Default:    ${manifest.default}`);
  console.log(`   Generated:  ${manifest.generated}`);
  console.log(`   Location:   ${OUTPUT_FILE}\n`);
  
  console.log('✨ All hardcoded language lists can now be removed!\n');
}

// Run
main();
